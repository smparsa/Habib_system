def seed_countries(apps, schema_editor):
    CountryTbl = apps.get_model("accounts", "CountryTbl")
    for fa, en in COUNTRIES:
        CountryTbl.objects.get_or_create(
            country_fa=fa, defaults={"country_en": en}
        )


def unseed_countries(apps, schema_editor):
    """حذف کشورهای این فهرست (به‌جز «ایران» و کشورهایی که استان دارند)."""
    CountryTbl = apps.get_model("accounts", "CountryTbl")
    fa_names = [fa for fa, _ in COUNTRIES if fa != "ایران"]
    CountryTbl.objects.filter(country_fa__in=fa_names).filter(
        provinces__isnull=True
    ).delete()


